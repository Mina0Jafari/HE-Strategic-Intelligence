
"""
Structured question interpretation for HE strategic intelligence.

The language model proposes the required evidence types and
statistical dimensions. Source IDs and provider identifiers are
validated against the existing registry and provider catalogue.

No numerical statistics are generated by this module.
"""
import json
import os

from pathlib import Path
from dotenv import load_dotenv
from openai import OpenAI

from ingestion.source_registry import SOURCE_REGISTRY
from ingestion.source_router import route_question
from ingestion.provider_resolver import providers_in_question

# Locate the project root from the ingestion/ folder.
PROJECT_ROOT = Path(__file__).resolve().parents[1]

# Load the existing project API credentials.
load_dotenv(PROJECT_ROOT / ".env")

ALLOWED_INDICATORS = {
    "Continuation",
    "Completion",
    "Progression",
}

ALLOWED_MODES = {
    "Full-time",
    "Part-time",
    "Apprenticeship",
}

ALLOWED_POPULATIONS = {
    "Taught",
    "Partnership",
    "TaughtOrRegistered_(TorR)",
}

ALLOWED_LEVELS = {
    "AllPostgraduates",
    "AllUndergraduates",
    "FirstDegree",
    "OtherPostgraduate",
    "OtherUndergraduate",
    "PGCE",
    "PostgraduateResearch",
    "PostgraduateTaughtMasters",
    "UndergraduateWithPostgraduateComponents",
}

ALLOWED_SOURCES = set(SOURCE_REGISTRY)


def validate_choice(value, allowed):
    """
    Accept only an exact supported category,
    ignoring capitalisation.

    Unknown values remain None and must not
    be passed to statistical analysis.
    """
    if not isinstance(value, str):
        return None

    for option in allowed:
        if option.casefold() == value.strip().casefold():
            return option

    return None


def fallback_plan(question):
    """
    Explainable non-LLM fallback.
    """
    routed = route_question(question)

    return {
        "question": question,
        "sources": routed["selected_sources"],
        "providers": routed["providers"],
        "indicator": None,
        "year": None,
        "population": None,
        "mode": None,
        "level": None,
        "comparison": len(routed["providers"]) > 1,
        "planning_method": "deterministic_fallback",
        "planning_error": None,
    }


def plan_question(question, model="gpt-4.1-mini"):
    """
    Produce a validated evidence request.

    Provider selection is controlled by the verified
    provider catalogue, not by invented LLM identifiers.
    """

    if not isinstance(question, str) or not question.strip():
        raise ValueError("A strategic question is required.")

    baseline = fallback_plan(question)
    verified_providers = providers_in_question(question)

    try:
        api_key = os.getenv("OPENAI_API_KEY")

        if not api_key:
            raise ValueError(
                "OPENAI_API_KEY was not loaded. "
                "Check the project .env file."
            )

        client = OpenAI(api_key=api_key)

        response = client.chat.completions.create(
            model=model,
            temperature=0,
            response_format={"type": "json_object"},
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You plan evidence retrieval for a "
                        "higher education decision-support system. "
                        "Do not invent statistics, provider IDs, "
                        "websites or unavailable reporting years. "
                        "Return only a JSON object with these keys: "
                        "sources, indicator, year, population, "
                        "mode, level, comparison. "
                        "sources must be a list selected from: "
                        + ", ".join(sorted(ALLOWED_SOURCES))
                        + ". indicator must be Continuation, "
                        "Completion, Progression or null. "
                        "population must be Taught, Partnership, "
                        "TaughtOrRegistered_(TorR) or null. "
                        "mode must be Full-time, Part-time, "
                        "Apprenticeship or null. "
                        "level must be one of: "
                        + ", ".join(sorted(ALLOWED_LEVELS))
                        + ". year must be the EXACT period explicitly "
                        "requested, otherwise null. "
                        "For example, do not convert 2024/25 into "
                        "2019-2022. "
                        "Do not select a particular university "
                        "unless the question explicitly identifies it. "
                        "Use ofs_outcomes for continuation/completion/"
                        "progression, ofs_nss for student-experience "
                        "survey indicators, hesa for enrolment and "
                        "entrant counts, govuk for government policy, "
                        "and institutional for local documents. "
                        "More than one source may be appropriate."
                    ),
                },
                {
                    "role": "user",
                    "content": question,
                },
            ],
        )

        proposed = json.loads(
            response.choices[0].message.content or "{}"
        )

        if not isinstance(proposed, dict):
            raise ValueError("Planner did not return an object.")

        raw_sources = proposed.get("sources", [])

        if not isinstance(raw_sources, list):
            raw_sources = []

        sources = [
            source
            for source in raw_sources
            if isinstance(source, str)
            and source in ALLOWED_SOURCES
        ]

        # Preserve validated deterministic matches too.
        for source in baseline["sources"]:
            if source not in sources:
                sources.append(source)

        if not sources:
            sources = ["institutional"]

        year = proposed.get("year")

        if not isinstance(year, str) or not year.strip():
            year = None
        else:
            year = year.strip()

            # Never accept a reporting period introduced
            # entirely by the model.
            if year not in question:
                year = None

        return {
            "question": question,
            "sources": sources,
            "providers": verified_providers,
            "indicator": validate_choice(
                proposed.get("indicator"),
                ALLOWED_INDICATORS,
            ),
            "year": year,
            "population": validate_choice(
                proposed.get("population"),
                ALLOWED_POPULATIONS,
            ),
            "mode": validate_choice(
                proposed.get("mode"),
                ALLOWED_MODES,
            ),
            "level": validate_choice(
                proposed.get("level"),
                ALLOWED_LEVELS,
            ),
            "comparison": (
                bool(proposed.get("comparison"))
                or len(verified_providers) > 1
            ),
            "planning_method": "validated_llm_plan",
            "planning_error": None,
            "usage": {
                "input_tokens": (
                    response.usage.prompt_tokens
                    if response.usage else 0
                ),
                "output_tokens": (
                    response.usage.completion_tokens
                    if response.usage else 0
                ),
            },
        }

    except Exception as error:
        baseline["planning_error"] = (
            f"{type(error).__name__}: {error}"
        )

        return baseline


if __name__ == "__main__":

    examples = [
        "How many students are enrolled at Anglia Ruskin University?",
        (
            "Compare student continuation rates at "
            "University of East London and "
            "Anglia Ruskin University."
        ),
        (
            "What government policies could affect "
            "university student retention?"
        ),
        (
            "What does the National Student Survey "
            "show about academic support?"
        ),
    ]

    for question in examples:
        print("\n" + "=" * 70)
        print(json.dumps(
            plan_question(question),
            indent=2,
        ))
